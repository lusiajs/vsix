// Writes src/logic/css-properties.ts from the DOM's CSSStyleDeclaration in lib.dom.d.ts.
// Run once after a TypeScript upgrade: bun editors/vscode/scripts/css-properties.ts
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";

const LEFT_OUT = new Set(["cssText", "cssFloat"]);
const libPath = join(import.meta.dir, "../../../node_modules/typescript/lib/lib.dom.d.ts");
const source = ts.createSourceFile(libPath, await Bun.file(libPath).text(), ts.ScriptTarget.Latest, true);

const names: string[] = [];
source.forEachChild((node) => {
  if (!ts.isInterfaceDeclaration(node) || node.name.text !== "CSSStyleDeclaration") return;
  for (const member of node.members) {
    if (!ts.isPropertySignature(member) || !member.type || member.type.kind !== ts.SyntaxKind.StringKeyword) continue;
    if (!ts.isIdentifier(member.name)) continue;
    const name = member.name.text;
    if (!LEFT_OUT.has(name)) names.push(name);
  }
});

const body = names.map((name) => `  "${name}",`).join("\n");
const out = `// Generated by editors/vscode/scripts/css-properties.ts from lib.dom.d.ts. Do not edit by hand.\nexport const CSS_PROPERTIES: readonly string[] = [\n${body}\n];\n`;
writeFileSync(join(import.meta.dir, "../src/logic/css-properties.ts"), out);
console.log(`wrote ${names.length} css properties`);
