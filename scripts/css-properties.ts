// Writes src/editor/css/ from the DOM's CSSStyleDeclaration in lib.dom.d.ts.
// Run once after a TypeScript upgrade: bun editors/vscode/scripts/css-properties.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";

const LEFT_OUT = new Set(["cssText", "cssFloat"]);
const HEADER = "// Generated by editors/vscode/scripts/css-properties.ts from lib.dom.d.ts. Do not edit by hand.";
const OUT_DIR = join(import.meta.dir, "../../../src/editor/css");
const libPath = join(import.meta.dir, "../../../node_modules/typescript/lib/lib.dom.d.ts");

// The first group whose pattern matches a name wins; the group without a pattern takes the rest.
const GROUPS: { file: string; constant: string; pattern?: RegExp }[] = [
  {
    file: "properties-border-background",
    constant: "BORDER_BACKGROUND_PROPERTIES",
    pattern: /^(webkit)?(Border|Outline|Background|Mask)|^(border|outline|background|mask)/,
  },
  {
    file: "properties-svg",
    constant: "SVG_PROPERTIES",
    pattern:
      /^(fill|stroke|stop|marker|colorInterpolation|dominantBaseline|alignmentBaseline|baselineShift|floodColor|floodOpacity|lightingColor|paintOrder|shapeRendering|vectorEffect|textAnchor|clipRule)|^(cx|cy|d|r|rx|ry|x|y)$/,
  },
  {
    file: "properties-effects",
    constant: "EFFECTS_PROPERTIES",
    pattern:
      /^(clipPath|filter|webkitFilter|backdropFilter|opacity|mixBlendMode|transform|webkitTransform|translate|rotate|scale|perspective|webkitPerspective|backfaceVisibility|webkitBackfaceVisibility|animation|webkitAnimation|transition|webkitTransition|offset|viewTransition|willChange|shape)/,
  },
  {
    file: "properties-box",
    constant: "BOX_PROPERTIES",
    pattern:
      /^(width|height|blockSize|inlineSize|min|max|margin|padding|boxSizing|boxDecorationBreak|boxShadow|webkitBoxShadow|webkitBoxSizing|overflow|overscroll|scroll|containIntrinsic|webkitLineClamp)/,
  },
  {
    file: "properties-text",
    constant: "TEXT_PROPERTIES",
    pattern:
      /^(font|text|letterSpacing|lineHeight|lineBreak|hyphen|wordBreak|wordSpacing|wordWrap|whiteSpace|widows|orphans|tabSize|quotes|list|ruby|unicodeBidi|webkitText|math|verticalAlign|page|break|printColorAdjust|counter|content|webkitTextSizeAdjust)/,
  },
  {
    file: "properties-layout",
    constant: "LAYOUT_PROPERTIES",
    pattern:
      /^(display|position|float|clear|top|right|bottom|left|inset|zIndex|isolation|direction|writingMode|order|webkitOrder|gap|rowGap|columnGap|columns?|column|tableLayout|captionSide|emptyCells|aspectRatio|visibility|objectFit|objectPosition|flex|webkitFlex|grid|contain$|container|align|webkitAlign|justify|webkitJustify|place|webkitBox(Align|Flex|OrdinalGroup|Orient|Pack))/,
  },
  { file: "properties-ui", constant: "UI_PROPERTIES" },
];

function groupFor(name: string) {
  return GROUPS.find((group) => !group.pattern || group.pattern.test(name)) ?? GROUPS[0];
}

async function readNames(): Promise<string[]> {
  const names: string[] = [];
  const source = ts.createSourceFile(
    libPath,
    await Bun.file(libPath).text(),
    ts.ScriptTarget.Latest,
    true,
  );
  source.forEachChild((node) => {
    if (!ts.isInterfaceDeclaration(node) || node.name.text !== "CSSStyleDeclaration") return;
    for (const member of node.members) {
      if (
        !ts.isPropertySignature(member) ||
        !member.type ||
        member.type.kind !== ts.SyntaxKind.StringKeyword
      )
        continue;
      if (!ts.isIdentifier(member.name)) continue;
      const name = member.name.text;
      if (!LEFT_OUT.has(name)) names.push(name);
    }
  });
  return names;
}

function groupModule(group: (typeof GROUPS)[number], names: string[]): string {
  const body = names.map((name) => `  "${name}",`).join("\n");
  return `${HEADER}\nexport const ${group.constant}: readonly string[] = [\n${body}\n];\n`;
}

function reexportModule(): string {
  const imports = GROUPS.map(
    (group) => `import { ${group.constant} } from "./${group.file}.ts";`,
  ).join("\n");
  const spreads = GROUPS.map((group) => `  ...${group.constant},`).join("\n");
  return `${HEADER}\n${imports}\n\nexport const CSS_PROPERTIES: readonly string[] = [\n${spreads}\n].sort();\n`;
}

const names = await readNames();
const namesByFile = new Map<string, string[]>(GROUPS.map((group) => [group.file, []]));
for (const name of names) namesByFile.get(groupFor(name).file)?.push(name);

mkdirSync(OUT_DIR, { recursive: true });
for (const group of GROUPS) {
  writeFileSync(join(OUT_DIR, `${group.file}.ts`), groupModule(group, namesByFile.get(group.file) ?? []));
}
writeFileSync(join(OUT_DIR, "css-properties.ts"), reexportModule());
console.log(`wrote ${names.length} css properties to ${GROUPS.length + 1} files`);
